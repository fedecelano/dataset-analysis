
"""Copy images referenced by cleaned GQA scene-graph splits.

Read image-ID lists generated by prepare_gqa_cleaning.py and copy
the corresponding source images into the cleaned dataset directory.

The operation is optional: cleaned annotations can also reference
the original image directory without creating image copies.

Source images and scene-graph annotations are never modified.

Usage (from the project root):
    python scripts/gqa_cleaning/extract_cleaned_gqa_images.py \
        --images-dir data/gqa/images \
        --cleaned-dir data/gqa_cleaned

Optional flags:
    --dry-run      Check files without copying or writing a report.
    --overwrite    Replace previously copied files with matching names.

Outputs:
    <cleaned-dir>/images/
    <cleaned-dir>/image_copy_report.json
"""

import argparse
import json
import shutil
from collections import Counter
from pathlib import Path


IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png")


def parse_args() -> argparse.Namespace:
    """Parse image-copying options."""
    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument(
        "--images-dir",
        type=Path,
        required=True,
        help="Directory containing the original GQA images.",
    )

    parser.add_argument(
        "--cleaned-dir",
        type=Path,
        required=True,
        help="Root directory of the cleaned GQA dataset.",
    )

    parser.add_argument(
        "--splits",
        nargs="+",
        default=["train", "val"],
        help="Image-ID lists to use (default: train val).",
    )

    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Check image availability without copying files.",
    )

    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing files with matching filenames.",
    )

    return parser.parse_args()


def validate_paths(
    images_dir: Path,
    cleaned_dir: Path,
) -> Path:
    """Ensure source images and copy destination are separate."""
    if not images_dir.is_dir():
        raise FileNotFoundError(
            f"Original image directory not found: {images_dir}"
        )

    if not cleaned_dir.is_dir():
        raise FileNotFoundError(
            f"Cleaned dataset directory not found: {cleaned_dir}"
        )

    destination = cleaned_dir / "images"

    if (
        images_dir == destination
        or images_dir in destination.parents
        or destination in images_dir.parents
    ):
        raise ValueError(
            "Source and destination image directories must be disjoint."
        )

    return destination


def validate_image_id(image_id: str) -> None:
    """Reject image IDs that cannot safely be used as filename stems."""
    if (
        not image_id
        or image_id in (".", "..")
        or "/" in image_id
        or "\\" in image_id
        or "\x00" in image_id
    ):
        raise ValueError(f"Invalid image ID: {image_id!r}")


def read_ids(
    cleaned_dir: Path,
    splits: list[str],
) -> tuple[set[str], dict[str, list[str]]]:
    """Read image IDs and identify duplicates within each split.

    Repeated IDs are reported, but each distinct image is copied
    at most once across all requested splits.
    """
    ids = set()
    duplicate_ids = {}

    for split in splits:
        path = cleaned_dir / "image_ids" / f"{split}.txt"

        if not path.is_file():
            raise FileNotFoundError(
                f"Missing image-ID list: {path}"
            )

        values = [
            line.strip()
            for line in path.read_text(
                encoding="utf-8"
            ).splitlines()
            if line.strip()
        ]

        for image_id in values:
            validate_image_id(image_id)

        counts = Counter(values)

        repeated = sorted(
            image_id
            for image_id, count in counts.items()
            if count > 1
        )

        duplicate_ids[split] = repeated
        ids.update(counts)

        print(
            f"{split}: {len(values)} referenced IDs "
            f"({len(counts)} unique, "
            f"{len(repeated)} repeated IDs)"
        )

    return ids, duplicate_ids


def index_images(
    images_dir: Path,
) -> dict[str, list[Path]]:
    """Index supported images by ID, without scanning subdirectories.

    Extensions are case-insensitive. Multiple files with the same
    stem are retained in the index and ordered by extension priority.
    """
    files_by_id = {}

    for path in images_dir.iterdir():
        if (
            not path.is_file()
            or path.suffix.lower() not in IMAGE_EXTENSIONS
        ):
            continue

        files_by_id.setdefault(path.stem, []).append(path)

    for paths in files_by_id.values():
        paths.sort(
            key=lambda path: (
                IMAGE_EXTENSIONS.index(path.suffix.lower()),
                path.name,
            )
        )

    return files_by_id


def main() -> None:
    """Copy selected images and generate a summary report."""
    args = parse_args()

    images_dir = args.images_dir.resolve()
    cleaned_dir = args.cleaned_dir.resolve()

    destination = validate_paths(images_dir, cleaned_dir)

    if len(set(args.splits)) != len(args.splits):
        raise ValueError("Duplicate splits requested.")

    for split in args.splits:
        if not split or not split.replace("_", "").isalnum():
            raise ValueError(f"Invalid split name: {split!r}")

    ids, duplicate_ids = read_ids(
        cleaned_dir,
        args.splits,
    )

    print("Indexing original images...")
    source_images = index_images(images_dir)

    # Detect existing files by image ID, regardless of extension.
    existing_images = (
        index_images(destination)
        if destination.is_dir()
        else {}
    )

    if not args.dry_run:
        destination.mkdir(parents=True, exist_ok=True)

    counts = Counter()
    missing_ids = []
    source_duplicate_files = {}
    destination_conflicts = {}

    for image_id in sorted(ids):
        sources = source_images.get(image_id, [])

        if not sources:
            counts["missing"] += 1
            missing_ids.append(image_id)
            continue

        if len(sources) > 1:
            source_duplicate_files[image_id] = [
                path.name for path in sources
            ]

        # Prefer .jpg, then .jpeg, then .png.
        source = sources[0]
        target = destination / source.name

        existing = existing_images.get(image_id, [])

        # Avoid creating multiple destination files for one image ID.
        conflicting = [
            path for path in existing
            if path.name != source.name
        ]

        if conflicting:
            counts["destination_conflicts"] += 1
            destination_conflicts[image_id] = [
                path.name for path in existing
            ]
            continue

        if target.exists() and not args.overwrite:
            counts["already_present"] += 1
            continue

        if args.dry_run:
            counts["would_copy"] += 1
            continue

        shutil.copy2(source, target)

        if target in existing:
            counts["overwritten"] += 1
        else:
            counts["copied"] += 1

        existing_images[image_id] = [target]

    report = {
        "source_images_dir": str(images_dir),
        "destination_images_dir": str(destination),
        "splits": args.splits,
        "unique_ids": len(ids),
        "dry_run": args.dry_run,
        "overwrite": args.overwrite,
        "counts": {
            key: counts[key]
            for key in (
                "copied",
                "overwritten",
                "already_present",
                "would_copy",
                "missing",
                "destination_conflicts",
            )
        },
        "missing_ids": missing_ids,
        "duplicate_ids_in_lists": duplicate_ids,
        "source_duplicate_files": source_duplicate_files,
        "destination_conflicts": destination_conflicts,
    }

    if not args.dry_run:
        report_path = cleaned_dir / "image_copy_report.json"

        report_path.write_text(
            json.dumps(
                report,
                indent=2,
                ensure_ascii=False,
            ),
            encoding="utf-8",
        )

        print(f"Report: {report_path}")

    print("===== GQA IMAGE EXTRACTION =====")
    print(f"Unique referenced IDs: {len(ids)}")
    print(f"Copied: {counts['copied']}")
    print(f"Overwritten: {counts['overwritten']}")
    print(f"Already present: {counts['already_present']}")
    print(f"Would copy: {counts['would_copy']}")
    print(f"Missing: {counts['missing']}")
    print(
        f"Destination conflicts: "
        f"{counts['destination_conflicts']}"
    )
    print(
        f"Source IDs with multiple files: "
        f"{len(source_duplicate_files)}"
    )

    if missing_ids:
        print(
            "First missing IDs: "
            + ", ".join(missing_ids[:10])
        )


if __name__ == "__main__":
    main()
