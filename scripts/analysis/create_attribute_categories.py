def build_attribute_to_category():
    """Create the mapping from each attribute to its semantic category."""

    mapping = {}

    for category, attributes in ATTRIBUTE_CATEGORIES.items():
        for attribute in attributes:
            if attribute in mapping:
                raise ValueError(
                    f"Attribute '{attribute}' appears in multiple categories."
                )

            mapping[attribute] = category

    return mapping


def main():
    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    df = pd.read_csv(INPUT_PATH)

    attribute_to_category = build_attribute_to_category()

    known_attributes = set(df["label"])

    # No attribute can be both categorized and ambiguous.
    ambiguous_overlap = (
        set(attribute_to_category)
        & AMBIGUOUS_ATTRIBUTES
    )

    if ambiguous_overlap:
        raise ValueError(
            "Some attributes are both categorized and marked as ambiguous:\n"
            + "\n".join(sorted(ambiguous_overlap))
        )

    # Every explicitly categorized attribute must exist in GQA.
    unknown_categorized = (
        set(attribute_to_category)
        - known_attributes
    )

    if unknown_categorized:
        raise ValueError(
            "Unknown attributes listed in ATTRIBUTE_CATEGORIES:\n"
            + "\n".join(sorted(unknown_categorized))
        )

    df["category"] = df["label"].map(
        attribute_to_category
    )

    df.loc[
        df["label"].isin(AMBIGUOUS_ATTRIBUTES),
        "category",
    ] = "other_ambiguous"

    # Every GQA attribute must now have an explicit assignment.
    unmapped = df[df["category"].isna()]

    if not unmapped.empty:
        raise ValueError(
            "Some attributes have not been categorized:\n"
            + "\n".join(unmapped["label"].tolist())
        )

    unknown_ambiguous = (
        AMBIGUOUS_ATTRIBUTES
        - set(df["label"])
    )

    if unknown_ambiguous:
        raise ValueError(
            "Unknown attributes listed as ambiguous:\n"
            + "\n".join(sorted(unknown_ambiguous))
        )

    # Sort attributes by training frequency for easier inspection.
    df = df.sort_values(
        "train_count",
        ascending=False,
    ).reset_index(drop=True)

    df.to_csv(
        CATEGORIZED_PATH,
        index=False,
    )

    category_summary = (
        df.groupby("category")
        .agg(
            num_labels=("label", "count"),
            train_instances=("train_count", "sum"),
            val_instances=("val_count", "sum"),
        )
        .reset_index()
    )

    category_summary["train_percentage"] = (
        category_summary["train_instances"]
        / category_summary["train_instances"].sum()*100
    )

    category_summary["val_percentage"] = (
        category_summary["val_instances"]
        / category_summary["val_instances"].sum()*100
    )

    category_summary[
        ["train_percentage", "val_percentage"]
    ] = category_summary[
        ["train_percentage", "val_percentage"]
    ].round(3)

    category_summary = category_summary.sort_values(
        "train_instances",
        ascending=False,
        )

    category_summary.to_csv(
        SUMMARY_PATH,
        index=False,
    )

    print(f"Saved: {CATEGORIZED_PATH}")
    print(f"Saved: {SUMMARY_PATH}")


if __name__ == "__main__":
    main()