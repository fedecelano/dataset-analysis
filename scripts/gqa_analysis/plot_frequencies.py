
"""Plot GQA label-frequency distributions from inspect_gqa.py CSV outputs.

For each annotation type (object classes, attributes, and relations),
generate two visualizations:

1. Independent train/validation rank-frequency distributions.
2. Relative frequencies of the top-N training labels across splits.

Counts represent annotation occurrences, not image-level prevalence.
The script reads precomputed CSV tables and never modifies the dataset.

Outputs are saved to:
    outputs/gqa_analysis/<dataset>/plots/

Usage:
    python scripts/gqa_analysis/plot_frequencies.py --dataset original
    python scripts/gqa_analysis/plot_frequencies.py --dataset cleaned --top-n 30
"""

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[2]
ANALYSIS_ROOT = PROJECT_ROOT / "outputs" / "gqa_analysis"

FREQUENCY_TABLES = (
    ("class_frequencies.csv", "Object Classes"),
    ("attribute_frequencies.csv", "Attributes"),
    ("relation_frequencies.csv", "Relations"),
)

REQUIRED_COLUMNS = ("label", "train_count", "val_count")


def parse_args() -> argparse.Namespace:
    """Parse dataset selection and plotting options."""
    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument(
        "--dataset",
        choices=("original", "cleaned"),
        default="original",
        help="Dataset version to analyze (default: original).",
    )

    parser.add_argument(
        "--top-n",
        type=int,
        default=30,
        help="Number of top training labels to display (default: 30).",
    )

    args = parser.parse_args()

    if args.top_n < 1:
        parser.error("--top-n must be a positive integer.")

    return args


def load_frequency_tables(
    input_dir: Path,
) -> list[tuple[str, pd.DataFrame]]:
    """Load and validate the frequency tables generated by inspect_gqa.py."""
    tables = []

    for filename, title in FREQUENCY_TABLES:
        path = input_dir / filename

        if not path.is_file():
            raise FileNotFoundError(
                f"Missing input file: {path}\n"
                "Run inspect_gqa.py with the same --dataset first."
            )

        try:
            df = pd.read_csv(path, dtype={"label": "string"})
        except pd.errors.EmptyDataError as exc:
            raise ValueError(f"Empty CSV file: {path}") from exc

        missing_columns = set(REQUIRED_COLUMNS) - set(df.columns)
        if missing_columns:
            raise ValueError(
                f"{path}: missing columns {sorted(missing_columns)}"
            )

        if df["label"].isna().any():
            raise ValueError(f"{path}: missing label values.")

        if df["label"].duplicated().any():
            raise ValueError(f"{path}: duplicate labels found.")

        for column in ("train_count", "val_count"):
            counts = pd.to_numeric(df[column], errors="coerce")

            if (
                counts.isna().any()
                or not np.isfinite(counts.to_numpy(dtype=float)).all()
                or (counts < 0).any()
                or (counts % 1 != 0).any()
            ):
                raise ValueError(
                    f"{path}: {column} must contain nonnegative integer counts."
                )

            df[column] = counts.astype("int64")

        tables.append((title, df))

    return tables


def plot_frequency_distributions(
    tables: list[tuple[str, pd.DataFrame]],
    output_dir: Path,
) -> Path:
    """Plot independent train/validation rank-frequency distributions.

    Each split is sorted independently by descending occurrence count.
    Zero counts are excluded because the frequency axis is logarithmic.
    """
    fig, axes = plt.subplots(1, 3, figsize=(24, 8))

    try:
        for ax, (title, df) in zip(axes, tables):
            for column, label in (
                ("train_count", "Train"),
                ("val_count", "Validation"),
            ):
                frequencies = np.sort(
                    df.loc[df[column] > 0, column].to_numpy(dtype=np.int64)
                )[::-1]

                if frequencies.size > 0:
                    ranks = np.arange(1, frequencies.size + 1)
                    ax.plot(ranks, frequencies, label=label)
                else:
                    ax.plot([], [], label=f"{label} (no occurrences)")

            ax.set_yscale("log")
            ax.set_xlabel("Label rank (independently sorted per split)")
            ax.set_ylabel("Number of occurrences")
            ax.set_title(title)
            ax.legend()
            ax.grid(axis="y", alpha=0.25)

            if not (df["train_count"].gt(0).any()
                    or df["val_count"].gt(0).any()):
                ax.text(
                    0.5,
                    0.5,
                    "No annotation occurrences",
                    ha="center",
                    va="center",
                    transform=ax.transAxes,
                )

        fig.suptitle(
            "GQA Label Rank-Frequency Distributions",
            fontsize=16,
        )
        fig.tight_layout(rect=(0, 0, 1, 0.95))

        output_path = output_dir / "frequency_distributions_combined.png"
        fig.savefig(output_path, dpi=200, bbox_inches="tight")

    finally:
        plt.close(fig)

    return output_path


def plot_top_labels_relative(
    tables: list[tuple[str, pd.DataFrame]],
    output_dir: Path,
    top_n: int = 30,
) -> Path:
    """Compare relative frequencies for the top-N training labels.

    Labels are selected using training counts only.

    Percentages are calculated independently for each split, using
    the total annotation occurrences of the corresponding label type.
    """
    fig, axes = plt.subplots(1, 3, figsize=(24, 10))

    try:
        for ax, (title, df) in zip(axes, tables):
            df = df.copy()

            train_total = int(df["train_count"].sum())
            val_total = int(df["val_count"].sum())

            df["train_percentage"] = (
                df["train_count"] / train_total * 100
                if train_total > 0
                else 0.0
            )

            df["val_percentage"] = (
                df["val_count"] / val_total * 100
                if val_total > 0
                else 0.0
            )

            selected = (
                df.loc[df["train_count"] > 0]
                .sort_values(
                    ["train_count", "label"],
                    ascending=[False, True],
                )
                .head(top_n)
                .iloc[::-1]
            )

            y = np.arange(len(selected))
            height = 0.4

            ax.barh(
                y - height / 2,
                selected["train_percentage"],
                height=height,
                label="Train",
            )

            ax.barh(
                y + height / 2,
                selected["val_percentage"],
                height=height,
                label="Validation",
            )

            ax.set_yticks(y)
            ax.set_yticklabels(selected["label"].astype(str))
            ax.set_xlabel("Percentage of annotations within split (%)")
            ax.set_title(title)
            ax.legend()

            if selected.empty:
                ax.text(
                    0.5,
                    0.5,
                    "No labels in training split",
                    ha="center",
                    va="center",
                    transform=ax.transAxes,
                )

            elif train_total == 0 or val_total == 0:
                missing_splits = []

                if train_total == 0:
                    missing_splits.append("train")
                if val_total == 0:
                    missing_splits.append("validation")

                ax.text(
                    0.02,
                    0.02,
                    f"No annotations in: {', '.join(missing_splits)}\n"
                    "Corresponding percentages are undefined.",
                    transform=ax.transAxes,
                    fontsize=9,
                    va="bottom",
                )

        fig.suptitle(
            f"GQA Top-{top_n} Training Labels: Relative Frequencies",
            fontsize=16,
        )
        fig.tight_layout(rect=(0, 0, 1, 0.95))

        output_path = output_dir / "top_labels_relative_combined.png"
        fig.savefig(output_path, dpi=200, bbox_inches="tight")

    finally:
        plt.close(fig)

    return output_path


def main() -> None:
    """Load frequency tables and generate the two combined figures."""
    args = parse_args()

    input_dir = ANALYSIS_ROOT / args.dataset / "tables"
    output_dir = ANALYSIS_ROOT / args.dataset / "plots"

    tables = load_frequency_tables(input_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"Dataset: {args.dataset}")

    frequency_plot = plot_frequency_distributions(tables, output_dir)
    print(f"Saved: {frequency_plot}")

    top_labels_plot = plot_top_labels_relative(
        tables,
        output_dir,
        args.top_n,
    )
    print(f"Saved: {top_labels_plot}")


if __name__ == "__main__":
    main()
